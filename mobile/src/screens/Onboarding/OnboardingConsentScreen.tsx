// ─────────────────────────────────────────────────────────────
interface PolicySectionProps {
  item: ConsentItem;
  content: string;
  isChecked: boolean;
  onCheck: () => void;
}

const PolicySection: React.FC<PolicySectionProps> = ({
  item,
  content,
  isChecked,
  onCheck,
}) => {
  const [expanded, setExpanded] = useState(false);
  const rotateAnim = useRef(new Animated.Value(0)).current;
  const checkScale = useRef(new Animated.Value(1)).current;

  const toggleExpand = () => {
    const toValue = expanded ? 0 : 1;
    Animated.spring(rotateAnim, {
      toValue,
      useNativeDriver: true,
      speed: 20,
    }).start();
    setExpanded(!expanded);
  };

  const handleCheck = () => {
    Animated.sequence([
      Animated.timing(checkScale, {toValue: 0.8, duration: 80, useNativeDriver: true}),
      Animated.spring(checkScale, {toValue: 1, useNativeDriver: true, speed: 25}),
    ]).start();
    onCheck();
  };

  const rotate = rotateAnim.interpolate({
    inputRange: [0, 1],
    outputRange: ['0deg', '180deg'],
  });

  return (
    <View style={styles.policyCard}>
      {/* Card Header */}
      <TouchableOpacity
        style={styles.policyHeader}
        onPress={toggleExpand}
        activeOpacity={0.8}
        accessibilityRole="button"
        accessibilityLabel={`${item.title} — tap to expand`}>
        <View style={[styles.policyIconBadge, {backgroundColor: item.color + '20'}]}>
          <Icon name={item.icon} size={22} color={item.color} />
        </View>
        <View style={styles.policyMeta}>
          <Text style={styles.policyTitle}>{item.title}</Text>
          <Text style={styles.policySubtitle}>{item.subtitle}</Text>
        </View>
        <Animated.View style={{transform: [{rotate}]}}>
          <Icon name="chevron-down" size={20} color={Colors.textTertiary} />
        </Animated.View>
      </TouchableOpacity>

      {/* Expandable Content */}
      {expanded && (
        <View style={styles.policyContent}>
          <ScrollView
            style={styles.policyScroll}
            nestedScrollEnabled
            showsVerticalScrollIndicator={true}
            scrollIndicatorInsets={{right: 1}}>
            <Text style={styles.policyText}>{content}</Text>
          </ScrollView>
          <View style={styles.policyReadNote}>
            <Icon name="check-circle-outline" size={13} color={Colors.success} />
            <Text style={styles.policyReadNoteText}>
              Please read the full policy above before accepting
            </Text>
          </View>
        </View>
      )}

      {/* Accept Checkbox Row */}
      <TouchableOpacity
        style={styles.checkRow}
        onPress={handleCheck}
        activeOpacity={0.8}
        accessibilityRole="checkbox"
        accessibilityState={{checked: isChecked}}
        accessibilityLabel={`I have read and accept the ${item.title}`}>
        <Animated.View
          style={[
            styles.checkbox,
            isChecked && styles.checkboxChecked,
            {transform: [{scale: checkScale}]},
          ]}>
          {isChecked && (
            <Icon name="check-bold" size={13} color={Colors.textInverse} />
          )}
        </Animated.View>
        <Text style={[styles.checkLabel, isChecked && styles.checkLabelChecked]}>
          I have read and agree to the{' '}
          <Text style={[styles.checkLabelBold, {color: item.color}]}>
            {item.title}
          </Text>
        </Text>
      </TouchableOpacity>
    </View>
  );
};

