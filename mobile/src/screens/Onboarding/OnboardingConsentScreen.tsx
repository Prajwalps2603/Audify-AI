interface OnboardingConsentScreenProps {
  onAccept: () => void;
}

const OnboardingConsentScreen: React.FC<OnboardingConsentScreenProps> = ({
  onAccept,
}) => {
  const [checked, setChecked] = useState({
    privacy: false,
    terms: false,
    guidelines: false,
  });
  const [isSubmitting, setIsSubmitting] = useState(false);

  const allAccepted = checked.privacy && checked.terms && checked.guidelines;

  const toggle = (id: 'privacy' | 'terms' | 'guidelines') => {
    setChecked(prev => ({...prev, [id]: !prev[id]}));
  };

  const handleContinue = async () => {
    if (!allAccepted) return;
    setIsSubmitting(true);
    // Small delay for UX feedback, then callback
    setTimeout(() => {
      onAccept();
    }, 600);
  };

  const contentFor = (id: ConsentItem['id']) => {
    if (id === 'privacy') return PRIVACY_POLICY;
    if (id === 'terms') return TERMS_AND_CONDITIONS;
    return USAGE_GUIDELINES;
  };

  const acceptedCount = Object.values(checked).filter(Boolean).length;

  return (
    <SafeAreaView style={styles.safeArea} edges={['top', 'bottom']}>
      <StatusBar barStyle="light-content" />

      {/* ── Gradient-style Header ── */}
      <View style={styles.header}>
        <View style={styles.headerLogoRow}>
          <Image
            source={require('../../assets/logo_icon_transparent.png')}
            style={styles.logoMarkImage}
            resizeMode="contain"
          />
          <Text style={styles.headerBrand}>Audify AI</Text>
        </View>
        <Text style={styles.headerTitle}>Before You Begin</Text>
        <Text style={styles.headerSubtitle}>
          Please review and accept our policies to protect your privacy and ensure
          responsible use of the app.
        </Text>

        {/* Progress Pills */}
        <View style={styles.progressRow}>
          {CONSENT_ITEMS.map(item => (
            <View
              key={item.id}
              style={[
                styles.progressPill,
                checked[item.id] && {backgroundColor: item.color},
              ]}>
              {checked[item.id] ? (
                <Icon name="check" size={11} color="#fff" />
              ) : (
                <View style={styles.progressDot} />
              )}
            </View>
          ))}
          <Text style={styles.progressText}>{acceptedCount}/3 accepted</Text>
        </View>
      </View>

      {/* ── Scrollable Policy Sections ── */}
      <ScrollView
        style={styles.scrollArea}
        contentContainerStyle={styles.scrollContent}
        showsVerticalScrollIndicator={false}
        keyboardShouldPersistTaps="handled">

        <Text style={styles.sectionHint}>
          Tap each section to read, then check the box to accept.
        </Text>

        {CONSENT_ITEMS.map(item => (
          <PolicySection
            key={item.id}
            item={item}
            content={contentFor(item.id)}
            isChecked={checked[item.id]}
            onCheck={() => toggle(item.id)}
          />
        ))}

        {/* Disclaimer note */}
        <View style={styles.disclaimer}>
          <Icon name="information-outline" size={14} color={Colors.textTertiary} />
          <Text style={styles.disclaimerText}>
            By continuing, you confirm you are 18 years or older and have the
            authority to accept these terms on behalf of your organization.
          </Text>
        </View>

        {/* ── Continue Button ── */}
        <TouchableOpacity
          style={[
            styles.continueBtn,
            allAccepted ? styles.continueBtnActive : styles.continueBtnDisabled,
          ]}
          onPress={handleContinue}
          disabled={!allAccepted || isSubmitting}
          activeOpacity={0.85}
          accessibilityLabel="Continue to the app"
          accessibilityRole="button">
          {isSubmitting ? (
            <ActivityIndicator size="small" color="#fff" />
          ) : (
            <>
              <Icon
                name={allAccepted ? 'rocket-launch-outline' : 'lock-outline'}
                size={20}
                color={allAccepted ? '#fff' : Colors.textTertiary}
              />
              <Text
                style={[
                  styles.continueBtnText,
                  !allAccepted && styles.continueBtnTextDisabled,
                ]}>
                {allAccepted ? 'Continue to Audify AI' : 'Accept all policies to continue'}
              </Text>
            </>
          )}
        </TouchableOpacity>

        {/* Help & Support Contact Link */}
        <TouchableOpacity
          style={styles.helpRow}
          onPress={() =>
            Linking.openURL(
              'mailto:prajwalnair2603@gmail.com?subject=Audify%20AI%20Support',
            )
          }
          activeOpacity={0.7}
          accessibilityLabel="Contact support"
          accessibilityRole="button">
          <Icon name="email-outline" size={15} color="rgba(255, 255, 255, 0.7)" />
          <Text style={styles.helpText}>
            Need help? Contact{' '}
            <Text style={styles.helpEmail}>prajwalnair2603@gmail.com</Text>
          </Text>
        </TouchableOpacity>

        <View style={{height: 20}} />
      </ScrollView>
    </SafeAreaView>
  );
};

